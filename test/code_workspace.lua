local F = require("workspace_fixture")
local suite = F.suite("Code workspace")
local case, check = suite.case, suite.check
local function has(text, needle) return tostring(text):find(needle, 1, true) ~= nil end

case("live documents, stable views and source revision guards", function()
	local f = F.new(); local store = f.env.require("runtime/code_store")
	store.init(); local doc = store.active(); local id = doc.id
	assert(store.update(id, "local x = 1\nreturn x", { origin = "typing" }))
	check("unsaved live draft is immediately visible", store.resolve(id).source == "local x = 1\nreturn x" and doc.revision == 1)
	check("unguarded existing tool write refused", not store.update(id, "return 2", { origin = "tool" }))
	check("stale write refused", not store.update(id, "return 2", { expected_revision = 0, origin = "tool" }))
	assert(store.rename(id, "draft.lua")); assert(store.close(id))
	check("closing view keeps library document", store.resolve(id).source == "local x = 1\nreturn x" and #store.openIds() == 0)
	assert(store.select(id)); check("rename/reopen retains ID", store.activeId() == id)
	local second = assert(store.create("draft.lua", "return 3"))
	check("duplicate names need exact IDs", not store.resolve("draft.lua") and store.resolve(second.id) == second)
	f.healthy(); f.close()
end)

case("verified persistence, backup recovery and corrupt/future protection", function()
	local f = F.new(); local env, h = f.env, f.h
	local store, fs = env.require("runtime/code_store"), env.require("runtime/fsx")
	store.init(); local doc = store.active(); assert(store.update(doc.id, "return 'saved'", { origin = "typing" })); assert(store.saveNow())
	local raw = assert(fs.read("code/workspace.json")); check("two verified copies", fs.read("code/workspace.backup.json") == raw)
	local originalWrite = fs.write
	fs.write = function(path, content, options) if path:find("workspace", 1, true) then originalWrite(path, content:sub(1, 10), options); return true end; return originalWrite(path, content, options) end
	assert(store.update(doc.id, "return 'new draft'", { origin = "typing" }))
	check("truncated successful write is detected", not store.saveNow() and store.storage.state == "failed")
	check("draft stays exact", doc.source == "return 'new draft'")
	fs.write = originalWrite
	local other = F.new(); for path, content in pairs(h.files) do other.h.files[path] = content end
	local recovered = other.env.require("runtime/code_store"); recovered.init()
	check("valid backup wins over corrupt primary", recovered.active().source == "return 'saved'")
	assert(recovered.saveNow()); local preserved = false
	for path, content in pairs(other.h.files) do if path:find("recovery_", 1, true) and content == raw:sub(1, 10) then preserved = true end end
	check("corrupt original preserved", preserved)
	local future = F.new(); local futureFs = future.env.require("runtime/fsx")
	assert(futureFs.write("code/workspace.json", '{"version":999}'))
	local protected = future.env.require("runtime/code_store"); protected.init()
	check("future version protected", protected.storage.state == "protected" and not protected.saveNow())
	check("future data unchanged", futureFs.read("code/workspace.json") == '{"version":999}')
	f.close(); other.close(); future.close()
end)

