case("source versions, undo/redo and coherent proposal application", function()
	local f = F.new(); local store = f.env.require("runtime/code_store"); store.init(); local doc = store.active()
	assert(store.update(doc.id, "return 1")); local version = assert(store.saveVersion(doc.id, "One"))
	assert(store.update(doc.id, "return 2")); assert(store.undoSource(doc.id)); check("source undo", doc.source == "return 1")
	assert(store.redoSource(doc.id)); check("source redo", doc.source == "return 2")
	check("stale restore refused", not store.restoreVersion(doc.id, version.id, 0))
	assert(store.restoreVersion(doc.id, version.id, doc.revision))
	local proposal = assert(store.propose(doc.id, doc.revision, "return 9"))
	local events = 0; local off = store.changed:connect(function() events = events + 1; check("applied proposal absent at notification", #store.proposals(doc.id) == 0) end)
	assert(store.applyProposal(proposal.id)); off()
	check("one coherent apply event", events == 1 and doc.source == "return 9")
	check("repeat apply cannot change revision", not store.applyProposal(proposal.id))
	local stale = assert(store.propose(doc.id, doc.revision, "return 8")); assert(store.update(doc.id, "return 7"))
	check("stale proposal preserved for review", not store.applyProposal(stale.id) and #store.proposals(doc.id) == 1 and doc.source == "return 7")
	f.healthy(); f.close()
end)

case("lexer keeps raw bytes and diff preserves exact endings", function()
	local f = F.new(); local lexer = f.env.require("runtime/code_lexer"); local diff = f.env.require("runtime/code_diff")
	local source = "--[=[comment\nend ]=]\nlocal s = [==[<tag>&\n]==] and 0xff\r\n"
	local cache = lexer.scan(source); local lines = lexer.lines(source)
	check("raw lines round trip", table.concat(lines, "\n") == source)
	check("multiline comment state", cache.states[1] ~= "" and cache.states[2] == "")
	local colored = lexer.rich(cache.lines[3], cache.spans[3], { keyword = "#fff", string = "#abc" })
	check("rich text is escaped", has(colored, "&lt;tag&gt;&amp;") and has(colored, '<font color='))
	local edit = diff.compare("a\nb\n", "a\nc\n")
	check("diff records exact sources and changed rows", edit.before == "a\nb\n" and edit.after == "a\nc\n" and edit.added == 1 and edit.removed == 1)
	local huge = diff.compare(string.rep("a\n", 500), string.rep("b\n", 500))
	check("large comparison uses bounded replacement", huge.replacement == true and huge.after == string.rep("b\n", 500))
	f.close()
end)

case("typed actions keep immutable source and pass data without interpolation", function()
	local f = F.new(); local store, inputs, runner = f.env.require("runtime/code_store"), f.env.require("runtime/code_actions"), f.env.require("tools/code_runner")
	store.init(); local doc = store.active()
	assert(store.update(doc.id, "local input = ...; print(input.text, input.flag, input.number); return input.text"))
	local action = assert(store.saveAction(doc.id, "Typed", { { key = "text", type = "string", required = true }, { key = "flag", type = "boolean", default = false }, { key = "number", type = "number", min = 0, max = 5 }, { key = "optional", type = "boolean" } }))
	local old = action.source; assert(store.update(doc.id, "error('new source')"))
	check("action snapshot remains fixed", action.source == old)
	check("action update requires observed source revision", not store.saveAction(doc.id, "Typed", action.inputs, { id = action.id, expected_revision = action.revision }))
	local text = "'); error('injected'); --"
	local params = assert(inputs.parameters(action.inputs, { text = text, number = 0 }))
	check("optional/default/zero survive", params.flag == false and params.number == 0 and params.optional == nil)
	check("invalid and unknown inputs rejected", not inputs.parameters(action.inputs, { text = text, number = 10 }) and not inputs.parameters(action.inputs, { text = text, injected = 1 }))
	local snapshot = assert(runner.actionSnapshot(action.id, action.revision, { text = text, number = 0 }))
	local result = f.run(function() return runner.run(snapshot) end)
	check("input executed as data only", result.ok and has(result.text, text) and not has(result.text, "Runtime error"))
	f.healthy(); f.close()
end)

case("runner attribution, live output, reservation and Stop", function()
	local f = F.new(); local store, runner = f.env.require("runtime/code_store"), f.env.require("tools/code_runner")
	store.init(); local doc = store.active(); assert(store.update(doc.id, "print('before'); task.wait(1); return false, nil, 7, nil"))
	local revision = doc.revision; local id = assert(runner.start(doc.id))
	check("duplicate activation rejected", not runner.start(doc.id))
	assert(store.update(doc.id, "return 'changed'")); f.h.sched.advance(1.2)
	local run = runner.runs[#runner.runs]
	check("run keeps dispatched source revision", run.id == id and run.revision == revision and run.source:find("before", 1, true))
	check("live and final output retained", #run.output > 0 and has(run.result.text, "false\tnil\t7\tnil"))
	assert(store.update(doc.id, "while true do task.wait(0.1) end")); assert(runner.start(doc.id)); runner.stop(); f.h.sched.advance(0.4)
	check("Stop clears active run", not runner.busy() and runner.runs[#runner.runs].status == "aborted")
	f.healthy(); f.close()
end)

case("Code tools share the live store and bounded scoped detail reads", function()
	local f = F.new(); f.tools({ "coding", "instance", "remotes", "script" })
	local store = f.env.require("runtime/code_store"); store.init(); local doc = store.active()
	local first = f.dispatch("code_write", { document_id = doc.id, code = "return 11" })
	check("empty doc accepts first write", first.ok and doc.source == "return 11")
	check("read returns revision", f.dispatch("code_read", { document_id = doc.id }).data.revision == doc.revision)
	check("tool refuses stale revision", not f.dispatch("code_write", { document_id = doc.id, code = "return 22", expected_revision = 0 }).ok)
	local result = f.dispatch("code_run", { document_id = doc.id, expected_revision = doc.revision })
	check("code_run uses managed runner", result.ok and has(result.text, "11") and result.data.runId)
	local N = f.env.require("tools/native_helpers").forGroup("instance")
	local summary = N.result({ value = string.rep("long value ", 1000), truth = false }, "Large result")
	check("large result keeps a bounded reader reference", summary.data.readTool == "instance_result_read" and #f.h.json.encode(summary) < 6000)
	check("reader cannot cross disabled group boundary", not f.dispatch("workspace_result_read", { result_id = summary.data.resultId }).ok)
	local detail = f.dispatch("instance_result_read", { result_id = summary.data.resultId, path = { "truth" } })
	check("false survives retained lookup", detail.ok and detail.data.value == false)
	f.healthy(); f.close()
end)

case("large immutable file sources reuse references and never overwrite drafts", function()
	local f = F.new(); local fs = f.env.require("runtime/fsx"); local sources = f.env.require("runtime/script_sources")
	local content = string.rep("-- source\n", 29000); assert(fs.write("large.lua", content, { scope = "pastes" }))
	local before = 0; for _ in pairs(f.h.files) do before = before + 1 end
	local item = assert(sources.fromFile("pastes/large.lua"))
	local after = 0; for _ in pairs(f.h.files) do after = after + 1 end
	check("large file is reused", before == after and item.path == "pastes/large.lua")
	local page = assert(sources.read(item.id, 1, 6000)); check("source page bounded and exact", #page.text == 6000 and page.nextOffset == 6001)
	local bridge = f.env.require("tools/source_documents"); local opened = assert(bridge.open({ sourceId = item.id }))
	check("large source opens read-only by reference", opened.readOnly and opened.sourceId == item.id)
	local small = assert(sources.keep("return 1", "synthetic", "Small.lua")); local doc = assert(bridge.open({ sourceId = small.id }))
	local store = f.env.require("runtime/code_store"); assert(store.update(doc.documentId, "return 'user draft'"))
	local reopened = assert(bridge.open({ sourceId = small.id }))
	check("reopening source preserves edited draft", reopened.documentId ~= doc.documentId and store.resolve(doc.documentId).source == "return 'user draft'")
	f.close()
end)

case("all native Code destinations build and preserve text through navigation", function()
	local h = require("env").new(); h.setViewport(1280, 800)
	local app = assert(h.boot()); h.settle(0.5); app.app.show("code"); h.settle(0.3)
	local panel = assert(app.app.panels and app.app.panels.code or app.app.codePanel or app.app.currentPanel, "Code panel handle")
	-- Find the public native panel handle without reaching through GUI text.
	if not panel.navigate then panel = app.app.views and app.app.views.code or panel end
	local box = assert(h.byName("SourceInput", app.app.screen), "native source input")
	box.Text = "-- kept draft\nreturn 5"; h.settle(0.1)
	check("native editor is multiline and raw", box.MultiLine and not box.RichText and not box.TextWrapped)
	local env = app.env; local store = env and env.require("runtime/code_store")
	check("bundle exposes shared store", store and store.active().source == box.Text)
	for _, destination in ipairs({ "Explorer", "Remotes", "Output", "History", "Library", "Game changes", "Editor" }) do
		panel.navigate(destination); h.settle(0.2)
		check(destination .. " has native view", panel.views[destination] ~= nil)
	end
	check("navigation preserved source", store.active().source == "-- kept draft\nreturn 5")
	check("native fixtures have no async errors", #h.errors() == 0)
	check("native fixtures have valid property types", #h.instanceState.typeErrors == 0)
	app.unload()
end)

